def translate_ui(text: str, language_code: str) -> str:
    if language_code != "de" or not text:
        return text
    translated = text
    for source, target in sorted(DE_TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated
